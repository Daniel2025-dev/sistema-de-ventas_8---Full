create or replace function private.current_organization_ids()
returns setof uuid
language sql stable security definer set search_path = ''
as $$
  select u.organization_id from public.usuarios u
  where u.auth_user_id = (select auth.uid()) and u.activo = true
$$;

revoke all on function private.current_organization_ids() from public;
grant usage on schema private to authenticated;
grant execute on function private.current_organization_ids() to authenticated;

do $$
declare table_name text;
begin
  foreach table_name in array array[
    'empresa','usuarios','roles','moneda','categorias','sucursal','impuestos','clientes',
    'proveedores','inventario','caja','ventas','cotizaciones','pedidos','gastos'
  ] loop
    execute format('alter table public.%I enable row level security', table_name);
    execute format('drop policy if exists organization_access on public.%I', table_name);
    execute format(
      'create policy organization_access on public.%I for all to authenticated using (organization_id in (select private.current_organization_ids())) with check (organization_id in (select private.current_organization_ids()))',
      table_name
    );
  end loop;
end $$;

alter table permisos enable row level security;
alter table permisos_rol enable row level security;
create policy permisos_read on permisos for select to authenticated using (true);
create policy permisos_rol_read on permisos_rol for select to authenticated using (true);

